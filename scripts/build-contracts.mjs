// Maintainer-only artifact generator: `npm run build:contracts`.
// Compiles contracts/ with the pinned foundry profile and regenerates the
// committed TS artifact modules. CI re-runs this and fails on drift, the
// same way the dist freshness gate works.
import { execSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const contractsDir = join(repoRoot, 'contracts');

execSync('forge build --force', { cwd: contractsDir, stdio: 'inherit' });

const artifact = (file, contract) =>
  JSON.parse(readFileSync(join(contractsDir, 'out', file, `${contract}.json`), 'utf8'));

// keccak-free provenance: sha256 of the source is enough to detect drift and
// avoids a runtime dependency in this script.
const sourceHash = (file) =>
  createHash('sha256').update(readFileSync(join(contractsDir, file))).digest('hex');

const header = (sources) => `// GENERATED by scripts/build-contracts.mjs — do not edit.
// solc ${artifact('TestERC20.sol', 'TestERC20').metadata?.compiler?.version ?? '0.8.24'} via forge, profile contracts/foundry.toml.
// Source sha256: ${sources.map(([file, hash]) => `${file}=${hash}`).join(' ')}
`;

const erc20 = artifact('TestERC20.sol', 'TestERC20');
writeFileSync(
  join(repoRoot, 'src', 'contracts', 'test-erc20.ts'),
  `${header([['TestERC20.sol', sourceHash('TestERC20.sol')]])}
export const TEST_ERC20_SOLC_VERSION = '0.8.24';
export const TEST_ERC20_SOURCE_SHA256 = '${sourceHash('TestERC20.sol')}';
export const TEST_ERC20_ABI = ${JSON.stringify(erc20.abi)} as const;
export const TEST_ERC20_BYTECODE = '${erc20.bytecode.object}' as const;
`,
);

const vyper = artifact('TestFixtures.sol', 'VyperLayoutToken');
const shares = artifact('TestFixtures.sol', 'SharesToken');
const emitter = artifact('TestFixtures.sol', 'EventEmitter');
const reverter = artifact('TestFixtures.sol', 'Reverter');
writeFileSync(
  join(repoRoot, 'tests', 'contracts', 'fixtures.ts'),
  `${header([['TestFixtures.sol', sourceHash('TestFixtures.sol')]])}
export const VYPER_LAYOUT_TOKEN_ABI = ${JSON.stringify(vyper.abi)} as const;
export const VYPER_LAYOUT_TOKEN_BYTECODE = '${vyper.bytecode.object}' as const;
export const SHARES_TOKEN_ABI = ${JSON.stringify(shares.abi)} as const;
export const SHARES_TOKEN_BYTECODE = '${shares.bytecode.object}' as const;
export const EVENT_EMITTER_ABI = ${JSON.stringify(emitter.abi)} as const;
export const EVENT_EMITTER_BYTECODE = '${emitter.bytecode.object}' as const;
export const REVERTER_ABI = ${JSON.stringify(reverter.abi)} as const;
export const REVERTER_BYTECODE = '${reverter.bytecode.object}' as const;
`,
);

console.log('Wrote src/contracts/test-erc20.ts and tests/contracts/fixtures.ts');
